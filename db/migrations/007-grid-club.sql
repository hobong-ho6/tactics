-- 007 · 실측 그리드의 실제 출처 클럽 (2026-08-11)
--
-- 사용자 지적: "아직 빌라에서 뛴 경기가 없는 선수들은 다른 팀의 히트맵을 그대로 쓰기에는 무리가 있으니
--              해당 선수들은 이전 팀 기록이라는 걸 기록해둬".
--
-- 왜 필요한가: 히트맵은 **그 팀의 전술이 만든 위치 분포**다. 같은 선수라도 팀이 바뀌면 달라진다
--   (실증: obs#156 — 만잠비의 스위스 대표팀 그리드는 바르가스가 좌측 폭을 고정으로 담당하는
--    구조의 산물이었다. 빌라에서 같은 모양이 나온다는 보장이 없다).
--   따라서 신규 합류 선수의 커널 적합값은 **"그 선수가 이전 팀에서 하던 일"의 적합**이지
--   "빌라에서 할 일"의 적합이 아니다. 이 구분을 페이지·평가에서 볼 수 있어야 한다.
--
-- ⚠️ `player_matches.team_code`로는 판별할 수 없다 — 그 컬럼은 **수집 배치 라벨**이라
--    타 클럽 시절 경기에도 현 소속 코드가 붙어 있다. 판별 근거는 `competition`(리그) 구성이다.
--
-- NULL = 현 소속 클럽 실측(캐비앗 없음).

ALTER TABLE squad_entries ADD COLUMN grid_club TEXT;    -- 실측 표본의 실제 소속 (예: 'SC Freiburg')
ALTER TABLE squad_entries ADD COLUMN grid_caveat TEXT;  -- 사람이 읽을 한 줄 경고

ALTER TABLE prescriptions ADD COLUMN grid_club TEXT;
