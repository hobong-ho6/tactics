/* 본문 텍스트에서 사전 표제어를 찾아 툴팁 표시로 감싼다.
   ⚠️ 긴 표제어부터 매칭한다 — '프레스 저항 캐리'가 '프레스 저항'에 먼저 잡히면 안 된다.
   ⚠️ 태그 안(속성값)은 건드리지 않는다. 같은 표제어는 문단당 첫 등장만 감싼다(밑줄 도배 방지). */
const KEYS = Object.keys(GLOSSARY).sort((a, b) => b.length - a.length);
const esc = s => s.replace(/[&<>"]/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]));
const RE = new RegExp(KEYS.map(k => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');

export function annotate(html){
  if (!html) return html;
  return html.split(/(<[^>]*>)/).map(part => {
    if (part.startsWith('<')) return part;
    const seen = new Set();
    return part.replace(RE, m => {
      if (seen.has(m)) return m;
      seen.add(m);
      return `<abbr class="gl" title="${esc(GLOSSARY[m])}">${m}</abbr>`;
    });
  }).join('');
}
